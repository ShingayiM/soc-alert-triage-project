"""
Data loading and preprocessing for the SOC Alert Triage project.

Dataset: NSL-KDD (a refined, de-duplicated successor to KDD Cup 1999).
Each row represents a network connection record; the label indicates whether
it is 'normal' traffic or a specific attack type. In this project, a
connection record stands in for a security alert generated by a monitoring
tool, and the classification task mirrors what a SOC analyst does when
triaging an alert queue: decide whether an alert reflects real malicious
activity (true positive) or benign activity (false positive).
"""

import pandas as pd
import numpy as np
from sklearn.preprocessing import LabelEncoder, StandardScaler

COLUMN_NAMES = [
    "duration", "protocol_type", "service", "flag", "src_bytes", "dst_bytes",
    "land", "wrong_fragment", "urgent", "hot", "num_failed_logins", "logged_in",
    "num_compromised", "root_shell", "su_attempted", "num_root",
    "num_file_creations", "num_shells", "num_access_files", "num_outbound_cmds",
    "is_host_login", "is_guest_login", "count", "srv_count", "serror_rate",
    "srv_serror_rate", "rerror_rate", "srv_rerror_rate", "same_srv_rate",
    "diff_srv_rate", "srv_diff_host_rate", "dst_host_count", "dst_host_srv_count",
    "dst_host_same_srv_rate", "dst_host_diff_srv_rate",
    "dst_host_same_src_port_rate", "dst_host_srv_diff_host_rate",
    "dst_host_serror_rate", "dst_host_srv_serror_rate", "dst_host_rerror_rate",
    "dst_host_srv_rerror_rate", "label",
]

CATEGORICAL_COLS = ["protocol_type", "service", "flag"]

# Mapping of fine-grained NSL-KDD attack labels to the standard 5-class
# taxonomy used in most NSL-KDD literature. Useful for multi-class analysis
# and for discussing alert *categories* in the report, even though the core
# prototype treats this as binary (normal vs attack / false positive vs
# true positive).
ATTACK_CATEGORY_MAP = {
    "normal": "normal",
    # DoS
    "back": "dos", "land": "dos", "neptune": "dos", "pod": "dos",
    "smurf": "dos", "teardrop": "dos", "mailbomb": "dos", "apache2": "dos",
    "processtable": "dos", "udpstorm": "dos",
    # Probe
    "satan": "probe", "ipsweep": "probe", "nmap": "probe", "portsweep": "probe",
    "mscan": "probe", "saint": "probe",
    # R2L (remote to local)
    "guess_passwd": "r2l", "ftp_write": "r2l", "imap": "r2l", "phf": "r2l",
    "multihop": "r2l", "warezmaster": "r2l", "warezclient": "r2l",
    "spy": "r2l", "xlock": "r2l", "xsnoop": "r2l", "snmpguess": "r2l",
    "snmpgetattack": "r2l", "httptunnel": "r2l", "sendmail": "r2l",
    "named": "r2l", "worm": "r2l",
    # U2R (user to root)
    "buffer_overflow": "u2r", "loadmodule": "u2r", "rootkit": "u2r",
    "perl": "u2r", "sqlattack": "u2r", "xterm": "u2r", "ps": "u2r",
}


def load_raw(train_path, test_path):
    train = pd.read_csv(train_path, header=None, names=COLUMN_NAMES)
    test = pd.read_csv(test_path, header=None, names=COLUMN_NAMES)
    return train, test


def add_category_column(df):
    df = df.copy()
    df["attack_category"] = df["label"].map(
        lambda x: ATTACK_CATEGORY_MAP.get(x, "unknown")
    )
    return df


def encode_and_scale(train, test):
    """
    Fit encoders/scaler on train only, apply to both, to avoid data leakage.
    Returns X_train, X_test, y_train, y_test (binary: 1 = attack, 0 = normal)
    plus fitted encoders for reuse (e.g. in a live-scoring demo).
    """
    train = train.copy()
    test = test.copy()

    y_train = (train["label"] != "normal").astype(int)
    y_test = (test["label"] != "normal").astype(int)

    feature_cols = [c for c in COLUMN_NAMES if c != "label"]
    X_train = train[feature_cols].copy()
    X_test = test[feature_cols].copy()

    encoders = {}
    for col in CATEGORICAL_COLS:
        le = LabelEncoder()
        le.fit(pd.concat([X_train[col], X_test[col]], axis=0))
        X_train[col] = le.transform(X_train[col])
        X_test[col] = le.transform(X_test[col])
        encoders[col] = le

    scaler = StandardScaler()
    numeric_cols = [c for c in feature_cols if c not in CATEGORICAL_COLS]
    X_train[numeric_cols] = scaler.fit_transform(X_train[numeric_cols])
    X_test[numeric_cols] = scaler.transform(X_test[numeric_cols])

    return X_train, X_test, y_train, y_test, encoders, scaler, feature_cols


